function setup() {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } })
  clients.push(client)
  let showHeader = true
  const tree = () => <StrictMode><QueryClientProvider client={client}><MemoryRouter>
    {showHeader && <AuthenticatedHeader />}<Link to="/settings">Autre page</Link><button>Action extérieure</button>
  </MemoryRouter></QueryClientProvider></StrictMode>
  const view = render(tree())
  return { client, ...view, update: () => view.rerender(tree()),
    show: (visible: boolean) => { showHeader = visible; view.rerender(tree()) } }
}
const bell = () => screen.getByRole('button', { name: /^Notifications —/ })
const open = () => { fireEvent.click(bell()); return screen.getByRole('dialog', { name: 'Notifications' }) }
function deferred<T>() {
  let resolve!: (value: T) => void
  let reject!: (error: Error) => void
  const promise = new Promise<T>((done, fail) => { resolve = done; reject = fail })
  return { promise, resolve, reject }
}
function page(start: number, length: number, more = false): Center {
  const items = Array.from({ length }, (_, index) => {
    const row = announcementNotificationRow('announcement', start + index)
    return decodeNotificationCenter({ items: [{ ...row, title: `Événement ${start + index}` }], unread_count: '50', next_cursor: null }).items[0]!
  })
  const last = items.at(-1)
  return { items, unreadCount: '50', nextCursor: more && last ? { updatedAt: last.updatedAt, notificationKey: last.notificationKey } : null }
}

